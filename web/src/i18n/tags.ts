// Un tag déjà en français (ComicInfo, édition) retrouve son mot de source : « Comédie » et
// « Comedy » sont le même tag. Le premier mot anglais l'emporte quand deux ont la même traduction.
const BACK = new Map<string, string>()
for (const [word, fr] of Object.entries(FR)) if (!BACK.has(fold(fr))) BACK.set(fold(fr), word)

/** Le mot de source d'un tag : son anglais s'il est une traduction connue, sinon lui-même. */
export const canonicalTag = (tag: string): string => BACK.get(fold(tag)) ?? tag

/** Le tag tel qu'il s'affiche dans la langue `lang`. */
export const tagLabel = (tag: string, lang: string): string => {
  const word = canonicalTag(tag)
  return lang === 'fr' ? (FR[word] ?? word) : word
}

/** Toutes les graphies connues d'un tag (mot de source et traduction), pour la recherche. */
export const tagSpellings = (tag: string): string[] => {
  const word = canonicalTag(tag)
  return FR[word] ? [word, FR[word]] : [word]
}
